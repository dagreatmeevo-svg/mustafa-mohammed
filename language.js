const languageSwitch = document.querySelector('.language-switch');
const localizedText = [];
for (const root of [document.querySelector('head title'), document.body]) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const english = node.nodeValue.trim();
    if (Object.hasOwn(arabic, english)) localizedText.push({ node, english, original: node.nodeValue });
  }
}
const localizedLabels = [...document.querySelectorAll('[aria-label]')].map(element => ({
  element, english: element.getAttribute('aria-label'),
}));

function translate(english) {
  return document.documentElement.lang === 'ar' && Object.hasOwn(arabic, english) ? arabic[english] : english;
}

function setLanguage(language) {
  const isArabic = language === 'ar';
  document.documentElement.lang = language;
  document.documentElement.dir = isArabic ? 'rtl' : 'ltr';
  localizedText.forEach(({ node, english, original }) => {
    node.nodeValue = original.replace(english, translate(english));
  });
  localizedLabels.forEach(({ element, english }) => {
    element.setAttribute('aria-label', translate(english));
  });
  languageSwitch.textContent = isArabic ? 'English' : 'العربية';
  languageSwitch.lang = isArabic ? 'en' : 'ar';
  try { localStorage.setItem('portfolio-language', language); } catch {}
  document.dispatchEvent(new Event('portfolio:languagechange'));
  document.fonts.ready.then(() => window.ScrollTrigger?.refresh());
}

languageSwitch.addEventListener('click', () => setLanguage(document.documentElement.lang === 'ar' ? 'en' : 'ar'));
try {
  if (localStorage.getItem('portfolio-language') === 'ar') setLanguage('ar');
} catch {}
